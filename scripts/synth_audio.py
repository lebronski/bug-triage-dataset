VOICES = ["ru", "ru+m3", "ru+f2", "ru+f4", "ru+m5"]
SPEEDS = [150, 140, 160, 145, 155]


def main(out: Path, espeak: str):
    out.mkdir(parents=True, exist_ok=True)
    rows, counters = [], {}
    for i, (cat, text) in enumerate(REPORTS):
        counters[cat] = counters.get(cat, 0) + 1
        voice, speed = VOICES[i % len(VOICES)], SPEEDS[i % len(SPEEDS)]
        d = out / cat
        d.mkdir(exist_ok=True)
        raw = d / f".{cat}_{counters[cat]:02d}.raw.wav"
        wav = d / f"{cat}_{counters[cat]:02d}.wav"
        subprocess.run([espeak, "-v", voice, "-s", str(speed), "-g", "4", "-w", str(raw), text], check=True)
        # 16 кГц, моно, PCM16 + 0,5 с тишины в начале и в конце, как в записи звонка
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(raw), "-af",
                        "adelay=500,apad=pad_dur=0.5,highpass=f=200,lowpass=f=3800",
                        "-ar", "16000", "-ac", "1", "-c:a", "pcm_s16le", str(wav)], check=True)
        raw.unlink()
        with wave.open(str(wav)) as w:
            dur = w.getnframes() / w.getframerate()
        rows.append({"file": f"{cat}/{wav.name}", "category": cat, "duration_sec": round(dur, 2),
                     "sample_rate": 16000, "channels": 1, "voice": voice, "speed_wpm": speed,
                     "source": "синтез речи espeak-ng по сценарию обращения", "transcript": text})
        print("ok", wav.name, f"{dur:.1f} c")
    with open(out.parent / "audio.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/audio/voice_reports", type=Path)
    ap.add_argument("--espeak", default="espeak-ng")
    a = ap.parse_args()
    main(a.out, a.espeak)
